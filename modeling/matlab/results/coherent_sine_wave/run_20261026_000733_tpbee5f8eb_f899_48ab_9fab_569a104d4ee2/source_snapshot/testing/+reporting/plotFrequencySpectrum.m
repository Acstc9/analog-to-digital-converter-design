function figureHandle = plotFrequencySpectrum(result, visibility)
arguments
    result (1,1) struct
    visibility (1,1) string {mustBeMember(visibility,["on","off"])} = "on"
end
spectrum = result.spectrum;
metrics = spectrum.metrics;
analysisSettings = spectrum.analysisSettings;
frequencyKilohertz = spectrum.frequencyHz / 1e3;
figureHandle = figure('Visible',visibility,'Name','Converter Frequency Spectrum','NumberTitle','off', ...
    'Color','w','Position',[100 100 1280 720]);
axes('Parent',figureHandle,'Position',[0.075 0.17 0.65 0.66]);
plot(frequencyKilohertz,spectrum.binPowerDbfs,'LineWidth',0.7,'DisplayName','Spectrum');
hold on;
fundamentalIndex = spectrum.fundamentalBin + 1;
plot(frequencyKilohertz(fundamentalIndex),spectrum.binPowerDbfs(fundamentalIndex), ...
    'ro','MarkerSize',7,'LineWidth',1.2,'DisplayName','Fundamental');
harmonicIndices = spectrum.harmonics.BinIndexZeroBased + 1;
visibleHarmonics = spectrum.binPowerVoltsSquared(harmonicIndices) > 0;
harmonicIndices = harmonicIndices(visibleHarmonics);
plot(frequencyKilohertz(harmonicIndices),spectrum.binPowerDbfs(harmonicIndices), ...
    'v','Color',[0.75 0.35 0.05],'MarkerSize',7,'DisplayName','Harmonics');
text(frequencyKilohertz(harmonicIndices),spectrum.binPowerDbfs(harmonicIndices) + 4, ...
    compose('H%d',spectrum.harmonics.Order(visibleHarmonics)), ...
    'HorizontalAlignment','center','VerticalAlignment','bottom','FontSize',10);
spurIndices = find(spectrum.spurBinMask);
[largestSpurPower, relativeSpurIndex] = max(spectrum.binPowerVoltsSquared(spurIndices));
if largestSpurPower > 0
    largestSpurIndex = spurIndices(relativeSpurIndex);
    plot(frequencyKilohertz(largestSpurIndex),spectrum.binPowerDbfs(largestSpurIndex), ...
        'kd','MarkerSize',10,'LineWidth',1.2,'DisplayName','Largest spur');
end
grid on;
xlabel('Frequency (kHz)');
ylabel('Power per frequency bin (dBFS)');
xlim(analysisSettings.analysisBandLimitsHz / 1e3);
lowerDisplayLimitDbfs = -160;
if isfinite(metrics.noiseFloorDbfsPerBin)
    lowerDisplayLimitDbfs = min(lowerDisplayLimitDbfs,10 * floor((metrics.noiseFloorDbfsPerBin - 20) / 10));
end
ylim([lowerDisplayLimitDbfs 5]);
legend('Location','southoutside','Orientation','horizontal');
title(sprintf('Ideal %d-bit successive-approximation converter', ...
    result.configuration.converter.resolutionBits));
subtitle({sprintf('Sample rate: %.3f million samples/s | Samples: %d | Input: %.6f kHz', ...
    result.configuration.sampling.sampleRateHz / 1e6,result.configuration.stimulus.sampleCount,result.stimulus.frequencyHz / 1e3), ...
    'Coherent sampling | Rectangular window | Unsmoothed spectrum'});
reportLines = { ...
    'INPUT SETTINGS', ...
    sprintf('Input amplitude: %g dBFS',result.configuration.stimulus.amplitudeDbfs), ...
    sprintf('Sine minimum: %.6g V',result.stimulus.offsetVolts - result.stimulus.peakAmplitudeVolts), ...
    sprintf('Sine maximum: %.6g V',result.stimulus.offsetVolts + result.stimulus.peakAmplitudeVolts), ...
    '', ...
    'PERFORMANCE', ...
    sprintf('SNR: %.2f dB',metrics.snrDb), ...
    sprintf('SINAD: %.2f dB',metrics.sinadDb), ...
    sprintf('THD: %.2f dBc',metrics.thdDb), ...
    sprintf('SFDR: %.2f dBc',metrics.sfdrDb), ...
    sprintf('ENOB: %.3f bits',metrics.enobBits), ...
    '(ENOB is amplitude corrected)', ...
    sprintf('Fundamental: %.2f dBFS',metrics.fundamentalDbfs), ...
    sprintf('Noise floor: %.2f dBFS/bin',metrics.noiseFloorDbfsPerBin), ...
    '', ...
    'ANALYSIS CONDITIONS', ...
    sprintf('Band: 0 to %.3f kHz',analysisSettings.analysisBandLimitsHz(2) / 1e3), ...
    'DC excluded from metrics', ...
    sprintf('Bin width: %.6g Hz',analysisSettings.frequencyBinWidthHz), ...
    sprintf('Noise bandwidth: %.6g Hz',analysisSettings.equivalentNoiseBandwidthHz), ...
    sprintf('Harmonic orders: %d to %d',analysisSettings.minimumHarmonicOrder,analysisSettings.maximumHarmonicOrder), ...
    '0 dBFS: full-scale sine power', ...
    'Largest spur includes harmonics'};
annotation(figureHandle,'textbox',[0.76 0.10 0.23 0.79],'String',reportLines, ...
    'Interpreter','none','FontSize',11,'EdgeColor','none','VerticalAlignment','top');
end
