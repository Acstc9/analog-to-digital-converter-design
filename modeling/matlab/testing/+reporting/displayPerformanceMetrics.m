function displayPerformanceMetrics(spectrum)
metricFields = {'snrDb'; 'snrFullScaleDb'; 'sinadDb'; 'thdDb'; 'sfdrDb'; ...
    'enobBits'; 'enobUncorrectedBits'; 'fundamentalDbfs'; ...
    'worstNonharmonicSpurDbc'; 'noiseFloorDbfsPerBin'; 'idealQuantizationSnrDb'};
metricDescriptions = ["Signal-to-noise ratio"; "Full-scale signal-to-noise ratio"; ...
    "Signal-to-noise-and-distortion ratio"; "Total harmonic distortion"; ...
    "Spurious-free dynamic range"; "Effective number of bits (amplitude corrected)"; ...
    "Effective number of bits (uncorrected)"; "Fundamental level"; ...
    "Largest nonharmonic spur level"; "Mean noise power per frequency bin"; ...
    "Ideal quantization signal-to-noise ratio (approximation)"];
metricUnits = ["dB"; "dB"; "dB"; "dBc"; "dBc"; "bits"; "bits"; ...
    "dBFS"; "dBc"; "dBFS/bin"; "dB"];
metricValues = cellfun(@(fieldName) spectrum.metrics.(fieldName),metricFields);
disp(table(metricDescriptions,metricValues,metricUnits, ...
    'VariableNames',{'Metric','Value','Unit'}));
fprintf('Harmonic components (levels relative to the fundamental):\n');
disp(spectrum.harmonics);
end
